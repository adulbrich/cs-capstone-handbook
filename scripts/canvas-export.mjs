function readPage(file) {
  const source = readFileSync(`${PAGES}/${file}`, "utf8");
  return parse(source.split(/^---$/m)[1]) ?? {};
}

function entries() {
  const all = [];
  for (const file of readdirSync(PAGES).filter((f) => f.endsWith(".mdx"))) {
    const data = readPage(file);
    const canvas = data.assignment?.canvas;
    if (!canvas) {
      continue;
    }
    const page = file.replace(/\.mdx$/, "");
    for (const row of canvasRows(canvas)) {
      row.weeks.forEach((week, i) => {
        all.push({
          families: canvas,
          family: row.family,
          level: data.assignment.level,
          name: row.names[i],
          page,
          term: row.term,
          week,
          weight: row.each,
        });
      });
    }
  }
  for (const z of ZERO_POINT) {
    all.push({ ...z, families: [], family: { name: z.name }, zero: true });
  }
  // Demo Day presenting is 1% extra credit in the term a team presents (#305),
  // outside the four components, so no frontmatter carries it.
  for (const term of TERMS) {
    all.push({
      extra: true,
      families: [],
      family: {
        group: "Extra Credit",
        name: "Demo Day Presentation",
        points: 100,
        submission: "none",
      },
      name: "Demo Day Presentation",
      page: "demo-day",
      term,
      week: term === "spring" ? 5 : 10,
      weight: 1,
    });
  }
  return all;
}

