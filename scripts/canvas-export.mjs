const pct = (n) => `${Number.parseFloat(n.toFixed(2))}%`;
const slug = (s) =>
  s
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
const isEl = (n) => n.type === "element";
const hasClass = (n, c) => (n.properties?.className ?? []).includes(c);
const termsIn = (s) =>
  [...s.matchAll(TERM_WORD)].map((m) => m[1].toLowerCase());
// Text mentions some term, but not this one: it belongs to another term.
const otherTerm = (s, term) => {
  const found = termsIn(s);
  return found.length > 0 && !found.includes(term);
};

