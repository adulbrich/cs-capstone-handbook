function termReadme(term, list) {
  const groups = new Map();
  for (const e of list.filter((x) => !(x.zero || x.extra))) {
    groups.set(e.family.group, (groups.get(e.family.group) ?? 0) + e.weight);
  }
  const total = [...groups.values()].reduce((a, b) => a + b, 0);
  const extra = list
    .filter((x) => x.extra)
    .reduce((sum, x) => sum + x.weight, 0);
  const rows = list.map((e) =>
    [
      e.file.slice(0, 2),
      e.name,
      e.zero ? "none (0 points, omit from final grade)" : e.family.group,
      e.zero ? 0 : e.family.points,
      e.zero ? "" : pct(e.weight),
      e.week +
        (e.family.peer_review_week
          ? `, reviews ${e.family.peer_review_week}`
          : ""),
      e.zero ? "" : [e.family.submission].flat().join(", "),
      e.family.rubric ? `\`${e.family.rubric.split("/")[1]}\`` : "none",
    ].join(" | ")
  );
  return `# ${cap(term)} (${COURSE[term]})

Generated by \`scripts/canvas-export.mjs\`; do not edit by hand.

## Canvas entries

| # | Entry | Group | Points | Weight | Due week | Submission | Rubric |
|---|---|---|---|---|---|---|---|
${rows.map((r) => `| ${r} |`).join("\n")}

## Assignment group weights

| Group | Weight |
|---|---|
${[...groups].map(([g, w]) => `| ${g} | ${pct(w)} |`).join("\n")}
| **Total** | **${pct(total)}** |
| Extra Credit (on top of the total) | ${pct(extra)} |
${OWNED[term] ? `\nThe rest of the term is ${OWNED[term]} (${pct(100 - total)}), built in Canvas by the co-instructor (#197); nothing for it here.\n` : ""}`;
}

