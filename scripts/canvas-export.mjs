// ---- trimming ------------------------------------------------------------------

// Index just past the section headed at top[i]: the next heading of the same
// or a higher level, or the end.
function sectionEnd(top, i) {
  const stops = top[i].tagName === "h2" ? ["h2"] : ["h2", top[i].tagName];
  let j = i + 1;
  while (j < top.length && !(isEl(top[j]) && stops.includes(top[j].tagName))) {
    j += 1;
  }
  return j;
}

function ops(root, where) {
  const top = root.children;
  const miss = (what) => warnings.push(`${where}: no match for ${what}`);
  const find = (id) => top.findIndex((n) => isEl(n) && n.properties.id === id);
  return {
    dropBlock(start, count = 1) {
      const i = top.findIndex(
        (n) => isEl(n) && text(n).trim().startsWith(start)
      );
      if (i < 0) {
        return miss(`block "${start}"`);
      }
      top.splice(i, count);
    },
    dropSection(id) {
      const i = find(id);
      if (i < 0) {
        return miss(`section #${id}`);
      }
      top.splice(i, sectionEnd(top, i) - i);
    },
    keepOnly(id) {
      const i = find(id);
      if (i < 0) {
        return miss(`section #${id}`);
      }
      top.splice(sectionEnd(top, i));
      top.splice(0, i);
    },
    renameHeading(id, label) {
      const i = find(id);
      if (i < 0) {
        return miss(`heading #${id}`);
      }
      top[i].children = [{ type: "text", value: label }];
    },
  };
}

// The heading text a family would give its own section: "Sprint Notes N".
const familyHeading = (f) => f.name.replace("{n}", "N");
const familyBase = (f) =>
  f.name.includes("{n}") ? f.name.slice(0, f.name.indexOf("{n}")) : null;

// An aside, table row, list item, or top-level paragraph about another term,
// another week, or another member of a numbered family.
function outOfScope(node, parent, { offTerm, otherMember, root, term }) {
  return (
    (hasClass(node, "starlight-aside") &&
      offTerm(text(select(".starlight-aside__title", node) ?? node))) ||
    (node.tagName === "tr" &&
      (() => {
        const first = node.children.find(isEl);
        const s = first ? text(first).trim() : "";
        return offTerm(s) || otherMember(s);
      })()) ||
    (node.tagName === "li" &&
      (() => {
        const m = text(node)
          .trim()
          .match(/^In (fall|winter|spring)\b/i);
        return Boolean(m && m[1].toLowerCase() !== term);
      })()) ||
    (node.tagName === "p" &&
      parent === root &&
      (() => {
        const s = text(node).trim();
        const lead = node.children.find(
          (c) => isEl(c) || (c.type === "text" && c.value.trim())
        );
        return (
          (lead?.tagName === "strong" && offTerm(text(lead))) || otherMember(s)
        );
      })())
  );
}

function dropOtherCourseColumns(root, term) {
  for (const table of selectAll("table", root)) {
    const head = select("tr", table)?.children.filter(isEl) ?? [];
    const off = head.map((c) => {
      const course = text(c).match(/CS 46[123]/);
      return course ? course[0] !== COURSE[term] : false;
    });
    if (off.some(Boolean)) {
      for (const tr of selectAll("tr", table)) {
        tr.children = tr.children.filter(isEl).filter((_, k) => !off[k]);
      }
    }
  }
}

function rubricHeadingsToGrading(top) {
  for (let i = 0; i < top.length; i += 1) {
    const n = top[i];
    const isRubric =
      isEl(n) &&
      ["h2", "h3"].includes(n.tagName) &&
      /^Rubric|\bRubric$/.test(text(n).trim());
    if (!isRubric) {
      continue;
    }
    const next = top[i + 1];
    if (!next || (isEl(next) && /^h[23]$/.test(next.tagName))) {
      top.splice(i, 1);
      i -= 1;
    } else {
      n.children = [{ type: "text", value: "Grading" }];
    }
  }
}

function trim(e, root) {
  const top = root.children;
  const { term, week, family } = e;
  const weeksInTerm = family.weeks?.[term]?.length ?? 1;

  // 1. Sections owned by another entry family on the same page. A heading
  // belongs to the family with the longest name it starts with.
  const owner = (heading) =>
    e.families
      .filter((f) => heading.startsWith(familyHeading(f)))
      .sort((a, b) => b.name.length - a.name.length)[0];
  // 2. Sections, asides, rows, bold-lead paragraphs about another term, or
  // another week of a numbered family ("Fall, week 10" in Repo Checkpoint 1).
  const offTerm = (s) => {
    if (otherTerm(s, term)) {
      return true;
    }
    const w = s.match(/^\W*(?:fall|winter|spring),? weeks? (\d+)\b/i);
    return Boolean(w && weeksInTerm > 1 && Number(w[1]) !== week);
  };
  // 3. Rows and paragraphs naming another member of a numbered family.
  const base = familyBase(family);
  const memberRe = base ? new RegExp(`^${base}(\\d+)\\b`) : null;
  const own = memberRe ? e.name.match(memberRe)?.[1] : null;
  const otherMember = (s) => {
    const m = memberRe ? s.match(memberRe) : null;
    return Boolean(m && m[1] !== own);
  };

  for (let i = 0; i < top.length; i += 1) {
    const n = top[i];
    if (!(isEl(n) && ["h2", "h3"].includes(n.tagName))) {
      continue;
    }
    const heading = text(n).trim();
    const f = n.tagName === "h2" ? owner(heading) : null;
    if ((f && f !== family) || offTerm(heading) || otherMember(heading)) {
      top.splice(i, sectionEnd(top, i) - i);
      i -= 1;
    }
  }

  const scope = { offTerm, otherMember, root, term };
  visit(root, "element", (node, index, parent) => {
    if (outOfScope(node, parent, scope)) {
      parent.children.splice(index, 1);
      return [SKIP, index];
    }
  });

  // 4. Columns headed by another term's course ("CS 462").
  dropOtherCourseColumns(root, term);

  OVERRIDES[family.name]?.(ops(root, `${term}/${e.name}`), e);

  // 5. Rubric headings: Canvas shows the attached rubric below the body, so
  // the table is gone. Keep the prose under "Grading", or drop an empty one.
  rubricHeadingsToGrading(top);
}

// ---- transform -------------------------------------------------------------------

function metaBox(e) {
  const row = (label, value) => [
    h("dt", { style: "font-weight:bold;" }, label),
    h("dd", { style: "margin:0 0 6px 0;" }, value),
  ];
  let submission;
  let due;
  let weight;
  if (e.zero) {
    ({ submission, due } = e);
    weight = "No points; it does not change your grade";
  } else if (e.extra) {
    submission = "Team; nothing to submit, your team presents at its session";
    due = "The Demo Day session your team registered for";
    weight = "1% extra credit in the term your team presents";
  } else {
    const kinds = [e.family.submission].flat();
    const who =
      e.level === "individual" || e.family.name.includes("Individual")
        ? "Individual"
        : "Team";
    submission =
      e.page === "project-partner-evaluation"
        ? "Completed by your project partner, not by you"
        : `${who}; ${kinds.map((k) => SUBMISSION[k] ?? k).join(" and ")}`;
    due = kinds.includes("survey")
      ? `${cap(e.term)}, closes end of week ${e.week}`
      : `${cap(e.term)}, week ${e.week}`;
    if (e.family.peer_review_week) {
      due += `; peer reviews end of week ${e.family.peer_review_week}`;
    }
    weight = `${pct(e.weight)} of the ${e.term} grade`;
  }
  return h("div", { style: BOX }, [
    h("dl", { style: "margin:0;" }, [
      ...row("Submission", submission),
      ...row("Due", due),
      ...row("Weight", weight),
    ]),
  ]);
}

function body(e) {
  const pageUrl = `${SITE}/assignments/${e.page}/`;
  const doc = fromHtml(
    readFileSync(`dist/assignments/${e.page}/index.html`, "utf8")
  );
  const root = select("div.sl-markdown-content", doc);
  if (!root) {
    throw new Error(`${e.page}: no .sl-markdown-content`);
  }

  // Tabs: keep the panel for this term, else show every panel under its label.
  visit(root, "element", (node, index, parent) => {
    if (node.tagName !== "starlight-tabs") {
      return;
    }
    const labels = selectAll('[role="tab"]', node).map((t) => text(t).trim());
    const panels = selectAll('[role="tabpanel"]', node);
    const k = labels.findIndex((l) => termsIn(l).includes(e.term));
    const flat =
      k >= 0
        ? panels[k].children
        : panels.flatMap((p, i) => [
            h("p", h("strong", labels[i])),
            ...p.children,
          ]);
    parent.children.splice(index, 1, ...flat);
    return [SKIP, index + flat.length];
  });

  // Code blocks: Expressive Code's frame, stylesheet link, token spans and
  // copy button become a plain <pre><code>, one line per source line.
  visit(root, "element", (node, index, parent) => {
    if (!hasClass(node, "expressive-code")) {
      return;
    }
    const lines = selectAll(".ec-line", node).map((l) => text(l));
    parent.children.splice(index, 1, h("pre", h("code", lines.join("\n"))));
    return [SKIP, index + 1];
  });

  // Drop what Canvas cannot use, the page's own meta and entry tables, and
  // the rubric tables; unwrap Starlight's heading wrapper.
  visit(root, "element", (node, index, parent) => {
    const drop =
      ["script", "style", "svg", "starlight-tabs-restore"].includes(
        node.tagName
      ) ||
      [
        "sl-anchor-link",
        "katex-html",
        "rubric",
        "assignment-meta",
        "canvas-entries",
      ].some((c) => hasClass(node, c));
    if (drop) {
      parent.children.splice(index, 1);
      return [SKIP, index];
    }
    if (hasClass(node, "sl-heading-wrapper")) {
      parent.children.splice(index, 1, ...node.children);
      return [SKIP, index];
    }
  });
  root.children = root.children.filter(
    (n) => !(n.type === "text" && !n.value.trim())
  );

  trim(e, root);

  visit(root, "element", (node) => {
    const p = node.properties;
    const style = (s) => {
      p.style = `${p.style ?? ""}${s}`;
    };
    if (hasClass(node, "starlight-aside")) {
      style(BOX);
      p.ariaLabel = undefined;
    }
    if (hasClass(node, "starlight-aside__title")) {
      style("font-weight:bold;margin-top:0;");
      p.ariaHidden = undefined;
    }
    if (node.tagName === "table") {
      style("border-collapse:collapse;width:100%;margin:12px 0;");
    }
    if (node.tagName === "th" || node.tagName === "td") {
      style(CELL);
    }
    for (const attr of ["href", "src"]) {
      const v = p[attr];
      if (typeof v === "string" && v.startsWith("/")) {
        p[attr] = SITE + v;
      } else if (typeof v === "string" && v.startsWith("#")) {
        p[attr] = pageUrl + v;
      }
    }
    p.className = undefined;
    p.dir = undefined;
    p.dataPagefindIgnore = undefined;
  });

  visit(root, "element", (node) => {
    if (
      node.tagName.includes("-") ||
      ["iframe", "img", "video", "details", "form", "button"].includes(
        node.tagName
      )
    ) {
      warnings.push(`${e.term}/${e.name}: unhandled <${node.tagName}>`);
    }
  });

  // A link only: once pasted, Canvas is authoritative (AGENTS.md hard rule 7).
  const source = h("p", [
    "Handbook page: ",
    h("a", { href: pageUrl }, text(select("h1", doc)).trim()),
  ]);
  return canvasHtml({
    children: [source, metaBox(e), ...root.children],
    type: "root",
  });
}

// Canvas's editor breaks on a tag split across lines ("</a\n  >") and on
// multi-line style attributes, which a code formatter produces. Re-serialize:
// whole tags, one-line styles, collapsed whitespace, one line per block.
function canvasHtml(tree) {
  visit(tree, "element", (node) => {
    const { style } = node.properties;
    if (typeof style === "string") {
      node.properties.style = style
        .split(";")
        .map((d) => d.replace(/\s+/g, " ").trim())
        .filter(Boolean)
        .join("; ");
    }
  });
  minifyWhitespace(tree);
  return `${tree.children.map((n) => toHtml(n)).join("\n")}\n`;
}

